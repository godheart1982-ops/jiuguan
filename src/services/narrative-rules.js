export const EVENT_SYSTEM_RULE = `**设计理念**

事件是生活的褶皱——不是弹窗通知，不是倒计时炸弹。它们像天气一样自然地来，有时候密集得喘不过气，有时候平静到让人以为什么都不会发生，然后一个转角就被兜头浇一身。

**不设固定触发条件。** 事件发生与否取决于叙事节奏的自然呼吸——当剧情需要一个转折、一次打断、一声闷雷时，它就来了。系统根据当前情绪浓度、关系张力、时间流逝自行判断是否引入事件，以及引入哪一层级的事件。

**事件层级**

**第一层·涟漪**

日子里的小石子。不改变任何关系走向，但给当下场景添一笔意外的色彩或打断一个正在酝酿的瞬间。可以是一次打断、一个闲笔、一点噪音——它是生活本身的底噪。

**第二层·暗涌**

开始搅动水面以下的东西。某条关系线出现了微妙的位移，或者某个被藏起来的东西多了一双可能看见它的眼睛。暗涌不会在气氛完全平静时强行插入——它只在某条线已经绷紧了一段时间后自然滑落，像拉满的弓弦上落了一只蚊子。

**第三层·地震**

不可回避的正面冲突。一旦发生就在记忆中永久留痕，改变至少一条关系线的根本走向。整个作品流程中可能只有两到三次，但每次都不可逆。

**运行规则**

- 涟漪随时可以来，甚至连续来，频率由场景的"日常浓度"决定；但同一轮内不宜超过 1 个，连续多轮都出现时应主动让位给暗涌或回归平静，避免底噪过载

- 暗涌需要前置张力的积累，它是压力锅上的那声细响

- 地震极少发生，且一旦发生，此后所有涟漪和暗涌的性质都会因它而改变

- 所有事件不预告、不提示，直接以叙事形式嵌入回复正文中

- 事件发生后的走向完全取决于玩家的选择——没有"正确答案"`;

export const RANDOM_NPC_RULE = `**核心原则：**

每个临时NPC不是工具人——即使只出场一次，也必须拥有最低限度的人格质感：一个名字、一个动机、一句只有这个人会说的台词。生成时不需要预设角色类型表，系统根据当前场景的物理环境和社交语境自动判断该出现什么样的人。

**四层生成逻辑：**

**① 日常遭遇层（高频/低戏剧性）**

与当前场景物理空间自然绑定的角色——玩家走到哪里，那个空间里本来就应该存在什么人，他们就是什么人。

- 生成标准：姓名（可只有姓）+ 一句话性格标签 + 一个只属于这个人的微小感官细节

- 叙事功能：提供环境质感、市井烟火气，偶尔因一句无心之语触发心理波动

**② 社交遭遇层（中频/中戏剧性）**

通过核心角色的社交网络延伸出的人物——不是凭空出现，而是从已有关系的边缘自然生长出来的。

- 生成标准：全名 + 年龄 + 职业 + 三句话性格素描 + 与主角或核心NPC之间的一个潜在摩擦点或连接点

- 叙事功能：推动社交线、信息流动、外部视角的引入

**③ 关系冲击层（低频/高戏剧性）**

对核心关系构成直接影响的人物——他们的出现意味着某条线即将被搅动。

- 生成标准：完整人物卡（按当前性别对应的状态栏模板完整输出——♀ 套用女性角色状态栏，♂ 套用主控/在场 NPC 状态栏），含外貌、身材数据、性格、动机、与主角的具体利害关系

- 叙事功能：直接推动核心矛盾和重大选择

**④ 幽灵层（极低频/氛围用）**

不直接互动但被提及的存在——通过他人口述、消息记录、社交动态间接浮现。从不正面出场，但其言论或行为可作为事件催化剂。

- 叙事功能：增加世界纵深感和不可见的压力源

**生成时机判定（自然逻辑）：**

- 玩家进入公共空间 → 该空间自然存在日常层NPC

- 核心NPC参与社交活动 → 社交层NPC自然浮现

- 某条关系线持续推进、积累了足够的深度和张力 → 冲击层NPC因果性地出现

- 作品中若存在秘密/隐藏信息类设定 → 当泄露风险积累到叙事需要的临界点时，关键NPC自动触发`;

