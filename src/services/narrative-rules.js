/**
 * 按 behavior 开关装配总则文本；总开关关或子开关全关时返回 ''（不注入）。
 * 子开关只留部分条目时，序号自动重排不留空号。
 */
export function buildImmersiveActingRule(behavior = {}) {
  if (behavior.immersiveActing === false) return '';
  const enabled = IMMERSIVE_ACTING_SECTIONS.filter((s) => behavior[s.key] !== false);
  if (!enabled.length) return '';
  return (
    IMMERSIVE_ACTING_HEADER + '\n\n' +
    enabled.map((s, i) => `${i + 1}. ${s.title}\n${s.body}`).join('\n\n')
  );
}

